-- Grapevine V28 Firebase Cloud Messaging device token table
-- Run in Supabase SQL Editor. RLS limits each member to their own device token rows.
create table if not exists public.device_tokens (
 id bigint generated by default as identity primary key,
 user_id uuid not null references auth.users(id) on delete cascade,
 token text not null unique,
 platform text not null default 'android',
 updated_at timestamptz not null default now(),
 created_at timestamptz not null default now()
);
alter table public.device_tokens enable row level security;
drop policy if exists "Members can manage their own push tokens" on public.device_tokens;
create policy "Members can manage their own push tokens" on public.device_tokens for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
grant select, insert, update, delete on public.device_tokens to authenticated;
grant usage, select on sequence public.device_tokens_id_seq to authenticated;
